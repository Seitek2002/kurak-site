/** Роль после «Ведёт: Имя,» со строчной буквы, но аббревиатуры (SMM, PR) не трогаем */
export const lowerFirst = (s: string) => (/^[A-ZА-ЯЁ]{2}/.test(s) ? s : s.charAt(0).toLowerCase() + s.slice(1));

/** «3 услуги», «1 кызмат» */
export function servicesCount(n: number, lang: Lang) {
  if (lang === "ky") return `${n} кызмат`;
  const m10 = n % 10, m100 = n % 100;
  const word = m10 === 1 && m100 !== 11 ? "услуга" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "услуги" : "услуг";
  return `${n} ${word}`;
}

