/**
 * Всё, что агентство ещё не прислало, хранится как Draft: значение-образец
 * плюс флаг. Пока draft = true, на сайте значение обведено пунктирным «стежком»
 * (компонент <Fill>), чтобы образец не приняли за факт. Прислали настоящее:
 * вписываете значение, ставите draft: false, пунктир исчезает.
 *
 * Список того, что нужно от агентства, — в README.md.
 */
export type Draft = { value: string; draft: boolean; note?: string };
const d = (value: string, note?: string): Draft => ({ value, draft: true, note });
const real = (value: string): Draft => ({ value, draft: false });

