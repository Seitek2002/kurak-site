/** Собрать план из ответов: без повторов, не больше пяти услуг */
export function buildPlan(business: string | null, needs: string[]): string[] {
  const out: string[] = [];
  const add = (ids?: string[]) => ids?.forEach((id) => !out.includes(id) && out.push(id));
  NEEDS.filter((n) => needs.includes(n.id)).forEach((n) => add(n.services));
  add(BUSINESS.find((b) => b.id === business)?.services);
  if (!out.length) add(["smm-strategy", "smm-target"]);
  return out.slice(0, 5);
}
