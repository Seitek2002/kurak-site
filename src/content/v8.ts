/** 1 услуга, 2 услуги, 5 услуг; по-кыргызски число не меняет слово */
export function countLabel(n: number, lang: Lang, ru: [string, string, string], ky: string) {
  if (lang === "ky") return `${n} ${ky}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const form = m10 === 1 && m100 !== 11 ? ru[0] : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? ru[1] : ru[2];
  return `${n} ${form}`;
}
export const servicesCount = (n: number, lang: Lang) => countLabel(n, lang, ["услуга", "услуги", "услуг"], "кызмат");

