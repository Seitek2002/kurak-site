/** Русское множественное число: 1 деталь, 2 детали, 5 деталей */
export function plural(n: number, forms: [string, string, string]) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}

/** «3 детали» / «3 деталь»: в кыргызском после числа существительное не меняется */
export function countPieces(n: number, lang: Lang) {
  return lang === "ky" ? `${n} деталь` : `${n} ${plural(n, ["деталь", "детали", "деталей"])}`;
}

