/** «4 услуги», «6 услуг»; по-кыргызски форма числа не меняется */
export function servicesCount(n: number, lang: Lang) {
  if (lang === "ky") return `${n} кызмат`;
  const mod10 = n % 10;
  const mod100 = n % 100;
  const word = mod10 === 1 && mod100 !== 11 ? "услуга" : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "услуги" : "услуг";
  return `${n} ${word}`;
}
